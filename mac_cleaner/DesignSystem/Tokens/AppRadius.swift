import CoreGraphics

enum AppRadius {
    /// 6pt — small chips / checkboxes
    static let xs: CGFloat = 6
    /// 8pt — compact controls
    static let sm: CGFloat = 8
    /// 10pt — buttons, search fields
    static let md: CGFloat = 10
    /// 12pt — segmented controls, badges
    static let lg: CGFloat = 12
    /// 14pt — list rows, smaller cards
    static let xl: CGFloat = 14
    /// 16pt — primary cards
    static let xxl: CGFloat = 16
    /// 18pt — large feature cards
    static let xxxl: CGFloat = 18

    static let card: CGFloat = 16
    static let button: CGFloat = 10
    static let control: CGFloat = 10
    static let badge: CGFloat = 7
}
